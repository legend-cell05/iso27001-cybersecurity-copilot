"""Writing a document, hashing it, and recording that it existed.

Every export goes through here, for one reason: an auditor reading a Statement
of Applicability six months from now needs to be able to ask *which state of
the ISMS produced this?* and get an answer. The export table records the
assessment it came from and the SHA-256 of the bytes that were written, so a
document that has been edited after the fact no longer matches its own record.

The other property worth the code is that exports are deterministic. The same
assessment produces byte-identical documents, so two exports that differ mean
the ISMS differed -- not that the tool felt differently on a Tuesday. That is
why nothing here writes a generation timestamp into the body of a document;
the timestamp belongs to the assessment, which already has one.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from sqlalchemy import text
from sqlalchemy.exc import SQLAlchemyError

from sentinel.config import Settings, get_settings
from sentinel.db.engine import get_engine
from sentinel.exceptions import DatabaseError
from sentinel.logging_config import get_logger

logger = get_logger(__name__)

KINDS = ("soa", "risk_treatment_plan", "findings", "audit_dossier", "posture")


def write_export(
    content: str,
    *,
    kind: str,
    filename: str,
    assessment_id: int | None,
    settings: Settings | None = None,
) -> tuple[Path, str]:
    """Write a document, hash it, and record it against its assessment."""
    settings = settings or get_settings()
    if kind not in KINDS:
        raise ValueError(f"unknown export kind {kind!r}")

    directory = settings.export_dir
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / filename
    payload = content.encode("utf-8")
    path.write_bytes(payload)
    digest = hashlib.sha256(payload).hexdigest()

    if assessment_id is not None:
        try:
            with get_engine(settings).begin() as conn:
                conn.execute(
                    text(
                        f"""INSERT INTO {settings.schema_name}.export
                            (assessment_id, kind, path, content_hash)
                            VALUES (:assessment_id, :kind, :path, :content_hash)"""
                    ),
                    {
                        "assessment_id": assessment_id,
                        "kind": kind,
                        "path": str(path),
                        "content_hash": digest,
                    },
                )
        except SQLAlchemyError as exc:
            raise DatabaseError(f"recording the export failed: {exc}") from exc

    logger.info(
        "export written",
        extra={"kind": kind, "path": str(path), "hash": digest[:12], "bytes": len(payload)},
    )
    return path, digest


def header(title: str, organisation: str, scope: str, assessment: dict[str, str]) -> list[str]:
    """The block every export starts with.

    Scope first, because a certificate is granted against a scope and a
    document that does not state one is describing nothing in particular. The
    catalogue fingerprint is there so that two documents claiming the same
    catalogue version can be told apart when they are not the same catalogue.
    """
    return [
        f"# {title}",
        "",
        f"**Organisation.** {organisation}",
        "",
        f"**ISMS scope.** {scope}",
        "",
        "| | |",
        "| --- | --- |",
        *[f"| {key} | {value} |" for key, value in assessment.items()],
        "",
        "> Generated by sentinel from the registers as they stood at the assessment above.",
        "> Synthetic data: this document describes a simulated organisation.",
        "",
    ]
